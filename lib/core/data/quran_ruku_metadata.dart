  static List<QuranRuku> forSurah(int surahNumber) {
    return all.where((ruku) => ruku.surahNumber == surahNumber).toList();
  }

  static List<QuranRuku> overlapping({
    required int surahNumber,
    required int startAyah,
    required int endAyah,
  }) {
    return all.where((ruku) => ruku.overlaps(surahNumber, startAyah, endAyah)).toList();
  }
}
