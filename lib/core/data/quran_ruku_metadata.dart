// Canonical Indo-Pak / Quran.com ruku partitions (558 rukus).
// Each entry is (surahNumber, startAyah, endAyah).
class QuranRuku {
  final int number;
  final int surahNumber;
  final int startAyah;
  final int endAyah;

  const QuranRuku({
    required this.number,
    required this.surahNumber,
    required this.startAyah,
    required this.endAyah,
  });

  int get ayahCount => endAyah - startAyah + 1;

  bool overlaps(int surah, int start, int end) {
    return surahNumber == surah && startAyah <= end && endAyah >= start;
  }
}

